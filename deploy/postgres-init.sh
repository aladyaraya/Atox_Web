#!/bin/sh
set -eu
# Passwords are generated as hex. Refuse characters unsafe for this init SQL.
case "$APP_DB_PASSWORD:$MIGRATOR_DB_PASSWORD" in *[!a-f0-9:]*|'') exit 1;; esac
[ "${#APP_DB_PASSWORD}" -ge 64 ] && [ "${#MIGRATOR_DB_PASSWORD}" -ge 64 ]
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE atox_migrator LOGIN PASSWORD '$MIGRATOR_DB_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE atox_app LOGIN PASSWORD '$APP_DB_PASSWORD' NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER DATABASE atox OWNER TO atox_migrator;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT ALL ON SCHEMA public TO atox_migrator;
GRANT USAGE ON SCHEMA public TO atox_app;
ALTER DEFAULT PRIVILEGES FOR ROLE atox_migrator IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atox_app;
ALTER DEFAULT PRIVILEGES FOR ROLE atox_migrator IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO atox_app;
SQL
